const DICTS: Record<Lang, Record<Key, string>> = { en, ta }

export const LANGS: { id: Lang; label: string }[] = [
  { id: 'en', label: 'English' },
  { id: 'ta', label: 'தமிழ்' },
]

export type T = (key: Key, vars?: Record<string, string | number>) => string

export function makeT(lang: Lang): T {
  const d = DICTS[lang]
  return (key, vars) => {
    let s = d[key] ?? en[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
    return s
  }
}

/** English, used for the small second line under labels when the app is in Tamil */
export const tEn = makeT('en')

export function useT(): { t: T; lang: Lang } {
  const s = useAppState()
  const lang = viewerOf(s).lang
  return { t: makeT(lang), lang }
}

export function categoryLabel(c: Category, t: T, vehicle?: Vehicle | null): string {
  if (c.name) return c.name
  if (c.builtIn === 'fuel') return vehicle ? t(`fuel.${vehicle.fuel}`) : t('cat.fuel')
  return c.builtIn ? t(`cat.${c.builtIn}`) : ''
}
